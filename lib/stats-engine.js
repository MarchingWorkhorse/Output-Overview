/**
 * dsh-code-stats — pure statistics engine.
 *
 * Input: a normalized list of file operations extracted from DSH session
 * logs, in chronological order. Output: aggregate statistics.
 *
 * Normalized operation shape:
 * {
 *   session: string,      // session id
 *   workspace: string,    // workspace slug (session store directory name)
 *   ts: number,           // epoch ms
 *   op: 'write' | 'edit' | 'replace',
 *   path: string,         // absolute file path as recorded in the tool call
 *   content: string,      // write: full new content; edit: '' (unused)
 *   oldString: string,    // replace: text removed
 *   newString: string,    // replace: text added
 *   ok: boolean,          // whether the tool result reported success
 * }
 *
 * Time windows: computeStats(operations, { from, to }) counts only
 * operations whose ts falls inside [from, to] (both inclusive; either bound
 * may be null). Content is ALWAYS replayed over the full history so that
 * window survival is measured against the file's true final state: a line
 * survives "in the window" only if it was generated by an in-window
 * operation AND is still present in the final content. Every line carries
 * the ts of the operation that produced it (line provenance).
 */

const DOC_EXTENSIONS = new Set([
  '.md', '.markdown', '.mdx', '.txt', '.rst', '.adoc', '.asciidoc',
]);

const IGNORED_PATH_RE = /(node_modules|\.dsh[\/\\]profiles|package-lock\.json|pnpm-lock\.yaml|\.lock$)/i;

export function isDocPath(path) {
  if (typeof path !== 'string') return false;
  const dot = path.lastIndexOf('.');
  if (dot === -1) return false;
  return DOC_EXTENSIONS.has(path.slice(dot).toLowerCase());
}

export function isIgnoredPath(path) {
  return typeof path === 'string' && IGNORED_PATH_RE.test(path);
}

function countLines(text) {
  if (typeof text !== 'string' || text.length === 0) return 0;
  const normalized = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const parts = normalized.split('\n');
  // A trailing newline does not start a new line.
  return parts[parts.length - 1] === '' ? parts.length - 1 : parts.length;
}

function normalizeText(s) {
  return String(s ?? '').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
}

/**
 * Classify one operation into per-bucket counters.
 * Returns null for operations that should be skipped entirely.
 */
export function classifyOp(op) {
  if (!op || typeof op.path !== 'string' || op.path.length === 0) return null;
  if (isIgnoredPath(op.path)) return null;
  if (op.ok === false) return null; // rejected / failed calls do not count as generated
  const doc = isDocPath(op.path);
  const bucket = doc ? 'doc' : 'code';
  if (op.op === 'write') {
    const lines = countLines(op.content);
    return { bucket, added: lines, removed: 0, files: 1 };
  }
  if (op.op === 'edit' || op.op === 'replace') {
    const added = countLines(op.newString);
    const removed = countLines(op.oldString);
    return { bucket, added, removed, files: 1 };
  }
  return null;
}

/** Split content into provenance lines: [{ t, ts }]. */
function toLines(content, ts) {
  if (typeof content !== 'string' || content.length === 0) return [];
  const parts = normalizeText(content).split('\n');
  if (parts[parts.length - 1] === '') parts.pop();
  return parts.map((t) => ({ t, ts }));
}

/** Append raw text as new provenance lines at the end of the file. */
function appendLines(file, text, ts) {
  if (text.length === 0) return;
  file.lines.push(...toLines(text, ts));
}

/**
 * Apply one literal substring replacement to the file's provenance lines,
 * matching str_replace_editor semantics. Returns whether the old text was
 * found. replaceAll replaces every occurrence left-to-right.
 *
 * char-offset → line mapping keeps the untouched head/tail of partially
 * replaced boundary lines with their ORIGINAL provenance; inserted lines
 * carry the replacing operation's ts.
 */
function applyReplace(file, oldString, newString, replaceAll, ts) {
  const oldText = normalizeText(oldString);
  const newText = normalizeText(newString);
  if (oldText.length === 0) {
    appendLines(file, newText, ts);
    return true;
  }
  let searchFrom = 0;
  let foundAny = false;
  for (let guard = 0; guard < 10_000; guard++) {
    // Search over the joined text plus a VIRTUAL trailing newline: the line
    // array does not store the file's final newline, but old_string values
    // produced by real edit calls legitimately end with one (e.g. deleting
    // whole lines). Without the virtual newline such matches never hit.
    const text = file.lines.map((l) => l.t).join('\n') + (file.lines.length > 0 ? '\n' : '');
    const at = text.indexOf(oldText, searchFrom);
    if (at === -1) break;
    foundAny = true;

    const lines = file.lines;
    const offsets = new Array(lines.length);
    let off = 0;
    for (let i = 0; i < lines.length; i++) {
      offsets[i] = off;
      off += lines[i].t.length + 1;
    }
    // First line containing a removed char.
    let s = 0;
    while (s + 1 < lines.length && offsets[s + 1] <= at) s++;
    // Last line containing a removed char (endChar is exclusive).
    const endChar = at + oldText.length;
    let e = s;
    while (e + 1 < lines.length && offsets[e + 1] < endChar) e++;

    const head = lines[s].t.slice(0, at - offsets[s]);
    const tail = lines[e].t.slice(Math.max(0, endChar - offsets[e]));
    const newParts = newText.length > 0 ? newText.split('\n') : [];
    const replacement = [];
    if (newParts.length === 0) {
      // Pure deletion: merge head and tail of the boundary lines.
      if (head.length > 0 || tail.length > 0) {
        replacement.push({
          t: head + tail,
          ts: head.length > 0 ? lines[s].ts : lines[e].ts,
        });
      }
    } else {
      const parts = newParts.map((t) => ({ t, ts }));
      if (head.length > 0) parts[0] = { t: head + parts[0].t, ts: parts[0].ts };
      if (tail.length > 0) parts[parts.length - 1] = { t: parts[parts.length - 1].t + tail, ts: parts[parts.length - 1].ts };
      replacement.push(...parts);
    }
    file.lines = lines.slice(0, s).concat(replacement, lines.slice(e + 1));

    if (!replaceAll) break;
    // Next search starts after the inserted text (contiguous chars starting
    // at offsets[s] + head.length, spanning newText.length).
    searchFrom = offsets[s] + head.length + newText.length;
  }
  if (!foundAny) {
    // The old text can no longer be located in the reconstructed content;
    // fall back to treating the edit as an append (best effort).
    appendLines(file, newText, ts);
  }
  return foundAny;
}

/**
 * Compute aggregate statistics over a chronological operation list.
 * @param {Array} operations normalized file operations (see file header)
 * @param {{ from?: number|null, to?: number|null }} opts inclusive epoch-ms window
 */
export function computeStats(operations, opts = {}) {
  const from = Number.isFinite(opts.from) ? opts.from : null;
  const to = Number.isFinite(opts.to) ? opts.to : null;
  const hasWindow = from !== null || to !== null;
  const inWindow = (ts) => ts > 0
    && (from === null || ts >= from)
    && (to === null || ts <= to);

  const buckets = {
    code: { generatedLines: 0, survivingLines: 0, files: new Map(), docFiles: new Set() },
    doc: { generatedLines: 0, survivingLines: 0, files: new Map(), docFiles: new Set() },
  };
  const perFile = new Map(); // path -> { lines: [{t, ts}], generated, ops, lastTs }
  const perSession = new Map(); // session -> { workspace, codeLines, docLines, files }
  const perDay = new Map(); // YYYY-MM-DD -> { codeLines, docLines }

  const touchSession = (id, workspace) => {
    if (!perSession.has(id)) perSession.set(id, { workspace, codeLines: 0, docLines: 0, files: new Set() });
    return perSession.get(id);
  };

  for (const op of operations) {
    const c = classifyOp(op);
    if (!c) continue;
    const ts = op.ts || 0;
    const win = hasWindow ? inWindow(ts) : true;
    const file = perFile.get(op.path) ?? { lines: [], generated: 0, ops: 0, lastTs: 0 };
    perFile.set(op.path, file);

    // Content replay always runs on the full history so the final state is
    // the file's true final state, independent of the window.
    if (op.op === 'write') {
      file.lines = toLines(op.content, ts);
    } else {
      applyReplace(file, op.oldString, op.newString, op.replaceAll === true, ts);
    }

    if (win) {
      const b = buckets[c.bucket];
      b.files.set(op.path, true);
      b.generatedLines += c.added;
      file.generated += c.added;
      file.ops += 1;
      file.lastTs = Math.max(file.lastTs, ts);

      const session = touchSession(op.session, op.workspace);
      session[c.bucket === 'doc' ? 'docLines' : 'codeLines'] += c.added;
      session.files.add(op.path);

      const day = ts ? new Date(ts).toISOString().slice(0, 10) : 'unknown';
      if (!perDay.has(day)) perDay.set(day, { codeLines: 0, docLines: 0 });
      perDay.get(day)[c.bucket === 'doc' ? 'docLines' : 'codeLines'] += c.added;

      if (c.bucket === 'doc') buckets.doc.docFiles.add(op.path);
    }
  }

  // Survival: lines still present, attributed to their producing operation.
  for (const [path, file] of perFile) {
    const bucket = isDocPath(path) ? buckets.doc : buckets.code;
    if (!hasWindow) {
      bucket.survivingLines += file.lines.length;
    } else {
      for (const line of file.lines) if (inWindow(line.ts)) bucket.survivingLines += 1;
    }
  }

  const sum = (b) => ({
    generatedLines: b.generatedLines,
    survivingLines: b.survivingLines,
    fileCount: b.files.size,
    survivalRate: b.generatedLines > 0 ? +(b.survivingLines / b.generatedLines).toFixed(4) : null,
  });

  const sessions = [...perSession.entries()].map(([id, v]) => ({
    id, workspace: v.workspace,
    codeLines: v.codeLines, docLines: v.docLines, fileCount: v.files.size,
  })).sort((a, b2) => b2.codeLines + b2.docLines - (a.codeLines + a.docLines));

  const files = [...perFile.entries()]
    .map(([path, f]) => ({
      path,
      doc: isDocPath(path),
      generated: f.generated,
      surviving: hasWindow ? f.lines.reduce((n, l) => n + (inWindow(l.ts) ? 1 : 0), 0) : f.lines.length,
      ops: f.ops,
      lastTs: f.lastTs,
    }))
    .filter((f) => f.generated > 0)
    .sort((a, b2) => b2.generated - a.generated);

  const days = [...perDay.entries()].sort((a, b2) => a[0] < b2[0] ? -1 : 1)
    .map(([date, v]) => ({ date, ...v }));

  return {
    code: sum(buckets.code),
    doc: { ...sum(buckets.doc), docFileCount: buckets.doc.docFiles.size },
    totals: {
      generatedLines: buckets.code.generatedLines + buckets.doc.generatedLines,
      survivingLines: buckets.code.survivingLines + buckets.doc.survivingLines,
      fileCount: buckets.code.files.size + buckets.doc.files.size,
    },
    window: { from, to },
    sessions, files: files.slice(0, 200), days,
    generatedAt: Date.now(),
  };
}
